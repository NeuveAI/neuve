import { posix } from "node:path";
import { z } from "zod";
import type { Declarations } from "./declarations.ts";
import type { HunkRecord } from "./hunks.ts";

/**
 * Change facts (10.22, PC3): size, spread, deletion-only hunks, new, deleted or renamed and binary
 * files, and the files the repository declares as tests, documentation or generated. They are
 * citable facts for the assessment, each with an ID and a plain statement, never combined into a
 * score: Assemble's lanes stay judgement over cited evidence (4.2, foundation 06).
 */

export const ChangeFact = z.strictObject({
  /** Stable within the manifest: `range.<fact>`, `file:<path>.<fact>` or `hunk:<id>.<fact>`. */
  id: z.string(),
  about: z.union([
    z.strictObject({ kind: z.literal("range") }),
    z.strictObject({ kind: z.literal("file"), path: z.string() }),
    z.strictObject({ kind: z.literal("hunk"), hunkId: z.string() }),
  ]),
  fact: z.string(),
  value: z.union([z.number(), z.boolean(), z.string(), z.array(z.string())]),
  statement: z.string(),
});
export type ChangeFact = z.infer<typeof ChangeFact>;

const plural = (count: number, one: string, many = `${one}s`) =>
  `${count} ${count === 1 ? one : many}`;

export const changeFacts = (
  hunks: ReadonlyArray<HunkRecord>,
  declarations: Pick<Declarations, "byPath">,
  reviewLines: number,
): ReadonlyArray<ChangeFact> => {
  const facts: Array<ChangeFact> = [];
  const range = { kind: "range" as const };
  const add = (
    about: ChangeFact["about"],
    fact: string,
    value: ChangeFact["value"],
    statement: string,
  ) => {
    const prefix =
      about.kind === "range"
        ? "range"
        : about.kind === "file"
          ? `file:${about.path}`
          : `hunk:${about.hunkId}`;
    facts.push({ id: `${prefix}.${fact}`, about, fact, value, statement });
  };
  const files = new Map<string, Array<HunkRecord>>();
  for (const hunk of hunks)
    files.set(hunk.path, [...(files.get(hunk.path) ?? []), hunk]);
  const directories = new Set(
    [...files.keys()].map((path) => posix.dirname(path)),
  );
  const added = hunks.reduce((sum, hunk) => sum + hunk.added, 0);
  const deleted = hunks.reduce((sum, hunk) => sum + hunk.deleted, 0);
  add(
    range,
    "spread",
    [...directories].sort(),
    `touches ${plural(files.size, "file")} in ${plural(directories.size, "directory", "directories")}`,
  );
  add(
    range,
    "changed-lines",
    added + deleted,
    `${added + deleted} changed lines (${added} added, ${deleted} deleted) in ${plural(hunks.length, "hunk")}`,
  );
  add(
    range,
    "review-lines",
    reviewLines,
    `${reviewLines} changed lines count toward the per-hunk allowance (9.27)`,
  );
  const deletionOnly = hunks.filter(
    (hunk) => hunk.kind === "text" && hunk.added === 0 && hunk.deleted > 0,
  );
  add(
    range,
    "deletion-only-hunks",
    deletionOnly.length,
    `${plural(deletionOnly.length, "hunk")} only delete${deletionOnly.length === 1 ? "s" : ""} lines`,
  );
  const declaredFiles = (kind: string) =>
    [...files.keys()].filter((path) =>
      (declarations.byPath.get(path) ?? []).some(
        (entry) => entry.kind === kind,
      ),
    );
  // A file only Linguist's lists mark (the `linguist` reader's suggestions carry `standard`) is
  // not one the repository declared, and the statement says so.
  const linguistOnly = (path: string) => {
    const generated = (declarations.byPath.get(path) ?? []).filter(
      (entry) => entry.kind === "generated",
    );
    return (
      generated.length > 0 &&
      generated.every((entry) => entry.standard !== undefined)
    );
  };
  for (const [kind, label] of [
    ["test", "declared as tests"],
    ["doc", "declared as documentation"],
    ["generated", "declared generated"],
  ] as const) {
    const paths = declaredFiles(kind);
    const marked = kind === "generated" ? paths.filter(linguistOnly) : [];
    add(
      range,
      `declared-${kind}-files`,
      paths,
      marked.length === 0
        ? `${plural(paths.length, "changed file")} ${label} by the repository`
        : `${plural(paths.length, "changed file")} declared generated by the repository or marked by GitHub Linguist's lists (${marked.length} by Linguist's lists alone)`,
    );
  }

  for (const [path, list] of files) {
    const first = list[0];
    if (first === undefined) continue;
    const about = { kind: "file" as const, path };
    const lines = list.reduce(
      (sum, hunk) => sum + hunk.added + hunk.deleted,
      0,
    );
    add(
      about,
      "changed-lines",
      lines,
      `${lines} changed lines in ${plural(list.length, "hunk")}`,
    );
    if (first.status === "added") add(about, "new", true, "a new file");
    if (first.status === "deleted")
      add(about, "deleted", true, "the file is deleted");
    if (first.status === "renamed")
      add(
        about,
        "renamed",
        first.oldPath ?? "",
        `renamed from ${first.oldPath ?? "?"}`,
      );
    if (first.status === "type-changed" || first.oldMode !== first.newMode)
      if (first.oldMode !== null && first.newMode !== null)
        add(
          about,
          "mode",
          `${first.oldMode}->${first.newMode}`,
          `mode changes from ${first.oldMode} to ${first.newMode}`,
        );
    if (first.kind === "binary") add(about, "binary", true, "binary content");
    // One fact per declared kind, citing every declaration of it (`linguist-generated` and
    // `-diff` both declare a file generated), so fact IDs stay unique.
    const byKind = new Map<string, Array<string>>();
    // Linguist's marks of the file (`standard`), by list, which the statement names as Linguist's.
    const byList = new Map<string, Array<string>>();
    for (const suggestion of declarations.byPath.get(path) ?? []) {
      byKind.set(suggestion.kind, [
        ...(byKind.get(suggestion.kind) ?? []),
        suggestion.by,
      ]);
      if (suggestion.standard !== undefined)
        byList.set(suggestion.standard, [
          ...(byList.get(suggestion.standard) ?? []),
          suggestion.by,
        ]);
    }
    for (const [kind, by] of byKind) {
      const lists = kind === "generated" ? [...byList] : [];
      const own = by.filter(
        (entry) => !lists.some(([, marks]) => marks.includes(entry)),
      );
      const linguist =
        lists.length === 0
          ? ""
          : `GitHub Linguist's ${lists.map(([list]) => (list === "linguist-vendored" ? "vendored" : "generated")).join(" and ")} ${lists.length === 1 ? "list marks" : "lists mark"} it (${lists.flatMap(([, marks]) => marks).join("; ")})`;
      add(
        about,
        `declared-${kind}`,
        by,
        own.length === 0 && linguist !== ""
          ? linguist
          : `the repository declares it ${kind === "doc" ? "documentation" : kind === "test" ? "a test" : "generated"} (${own.join("; ")})${linguist === "" ? "" : `, and ${linguist}`}`,
      );
    }
  }

  for (const hunk of hunks) {
    if (hunk.kind !== "text") continue;
    const about = { kind: "hunk" as const, hunkId: hunk.hunkId };
    add(
      about,
      "changed-lines",
      hunk.added + hunk.deleted,
      `${hunk.added + hunk.deleted} changed lines (${hunk.added} added, ${hunk.deleted} deleted)`,
    );
    if (hunk.added === 0 && hunk.deleted > 0)
      add(about, "deletion-only", true, "only deletes lines");
    if (hunk.enclosing !== null && hunk.enclosing.symbols.length > 0)
      add(
        about,
        "enclosing",
        hunk.enclosing.symbols,
        `inside ${hunk.enclosing.symbols.join(", ")}`,
      );
    else if (hunk.enclosing?.limitation)
      add(about, "enclosing", [], hunk.enclosing.limitation);
  }
  return facts;
};

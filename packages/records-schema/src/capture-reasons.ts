export const PublicRefusal = z
  .string()
  .max(4096)
  .refine((value) => {
    if (
      /^run [0-9A-HJKMNP-TV-Z]{26}: its run log names capture [a-f0-9]{64}, which is run [0-9A-HJKMNP-TV-Z]{26}'s$/.test(
        value,
      )
    )
      return true;
    if (
      CloseReasons.safeParse(value).success ||
      patterns.some((pattern) => pattern.test(value))
    )
      return true;
    const sdk =
      /^call \d+: (.*?); frame \d+ ([^/]+)\/([^;]+); callbacks \d+\/(?:\d+|unknown) \((?:retained-stream-prefix|retained-argument-escape)\); unavailable credential source census; source retained privately, export refused$/.exec(
        value,
      );
    return (
      sdk !== null &&
      SdkFailure.safeParse(sdk[1]).success &&
      SdkFrameType.safeParse(sdk[2]).success &&
      SdkFrameType.safeParse(sdk[3]).success
    );
  });


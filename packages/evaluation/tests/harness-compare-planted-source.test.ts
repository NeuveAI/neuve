// Why: a family's deviant must differ in code. A trailing comment is not code, so a copy apart only
// in its comment would build as a family whose "defect" is a comment; and a template string's
// interpolated expression is code, so `${a}` against `${b}` is a name apart, not a literal apart.
test("a family compares code: comments are dropped and interpolated expressions are names", () => {
  const copies = (rows: ReadonlyArray<string>) =>
    rows.map((row, i) => file(`internal/${"abcde"[i]}/limit.ts`, [row]));
  const same = "  const limit = check(size, 64);";
  expect(familyRow("x = 1 // was 10", true)).toBe(
    familyRow("x = 1 // was 100", true),
  );
  expect(familyRow('x = "a // b"', true)).toBe('ID = "a // b"');
  expect(familyRow("x = 1 # was 10", true, true)).toBe(
    familyRow("x = 1", true, true),
  );
  expect(
    familyPattern(
      copies([same, same, `${same} // was 100`, `${same} // was 10`, same]),
    ),
  ).toMatch(/exactly one copy/);
  // A real literal deviant still builds when the copies carry comments.
  expect(
    familyPattern(
      copies([
        `${same} // cap`,
        `${same} // cap`,
        "  const limit = check(size, 6); // cap",
        `${same} // cap`,
        `${same} // cap`,
      ]),
    ),
  ).toEqual({
    deviant: 2,
    paths: copies([same, same, same, same, same]).map((f) => f.path),
  });
  const template = (inner: string) => `  log(\`refused \${${inner}} bytes\`);`;
  expect(
    familyPattern(
      copies([
        template("size"),
        template("size"),
        template("length"),
        template("size"),
        template("size"),
      ]),
    ),
  ).toMatch(/exactly one copy/);
  expect(
    familyPattern(
      copies([
        template("size"),
        template("size + 1"),
        template("size"),
        template("size"),
        template("size"),
      ]),
    ),
  ).toMatch(/beyond literals/);
  // The template's own text is a literal: a copy apart there is a deviant.
  const text = (word: string) => `  log(\`${word} \${size} bytes\`);`;
  expect(
    familyPattern(
      copies([
        text("refused"),
        text("refused"),
        text("refused"),
        text("accepted"),
        text("refused"),
      ]),
    ),
  ).toMatchObject({ deviant: 3 });
});

// Why: the gate scores a family on its deviant's lines, so the record must key the deviating copy
// and index it correctly in its members. Keyed on the entry's first file, or with the index one off,
// every finding about the real defect would score as a miss.
test("a built family keys its deviating copy and indexes it among its members", async () => {
  const { buildSourceSet } =
    await import("../src/harness-compare/full-test/planted-source.ts");
  const { join } = await import("node:path");
  const { readFileSync, rmSync } = await import("node:fs");
  const limit = (pkg: string) =>
    `package ${pkg}\n\nfunc Limit(n int) bool {\n\treturn n <= 64\n}\n`;
  const dirs = ["p", "q", "r", "s", "t"];
  const { root, hosts, cases, plant } = await fixtureHost(
    Object.fromEntries(dirs.map((d) => [`${d}/limit.go`, limit(d)])),
  );
  try {
    const edit = (value: string) => [
      { find: "\treturn n <= 64", replace: `\treturn n <= ${value}` },
    ];
    const family: PlantSpec = {
      ...plant,
      variant: 150,
      category: "family",
      path: "p/limit.go",
      edits: edit("128"),
      extraFiles: [
        { path: "q/limit.go", edits: edit("128") },
        { path: "r/limit.go", edits: edit("128") },
        { path: "s/limit.go", edits: edit("12") },
        { path: "t/limit.go", edits: edit("128") },
      ],
      mentions: ["Limit"],
      message: "Allow larger inputs",
      difficulty: "plain",
    };
    const built = buildSourceSet({
      hostsRoot: hosts,
      casesRoot: cases,
      plants: [family],
      index: null,
    });
    const record = JSON.parse(
      readFileSync(join(built.results[0]!.directory, "planted.json"), "utf8"),
    );
    expect(record.lineKeys).toEqual(["s/limit.go:new:4"]);
    expect(record.family.deviant).toBe(3);
    expect(record.family.members.map((m: { path: string }) => m.path)).toEqual(
      dirs.map((d) => `${d}/limit.go`),
    );
    expect(record.family.members[record.family.deviant].path).toBe(
      record.lines[0].path,
    );
    expect(record.language).toBe("Go");
  } finally {
    rmSync(root, { recursive: true, force: true });
  }
});

// Why: a test-file plant's related code is the behaviour the new test fails to cover, and the gate
// reads it as behaviour the host's range changes. A related line beside the change, in a changed
// file but not a changed line, points the key at code the range never shows.
test("a test-file plant's related lines are lines the host's range changes", () => {
  const changed = (lines: ReadonlyArray<number>) => () => new Set(lines);
  const range = (startLine: number, lines: ReadonlyArray<string>) => [
    { path: "a.go", startLine, endLine: startLine + lines.length - 1, lines },
  ];
  expect(
    relatedOutsideRangeProblem(
      range(4, ["\tif n > 20 {", "\t\treturn false"]),
      changed([4, 5]),
    ),
  ).toBeNull();
  expect(
    relatedOutsideRangeProblem(
      range(4, ["\tif n > 20 {", "\t\treturn false"]),
      changed([4]),
    ),
  ).toMatch(/a\.go:5 is not a line the host's range changes/);
  // Blank and comment lines inside the range are not anchors and need not be changed.
  expect(
    relatedOutsideRangeProblem(
      range(3, ["\t// the cap", "\tif n > 20 {", ""]),
      changed([4]),
    ),
  ).toBeNull();
});


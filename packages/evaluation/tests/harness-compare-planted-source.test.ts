// Why (NEU-148, WP12, set C): the finders' gate scores a plant by its category, so three boundaries
// would corrupt it silently. A plant whose own diff has the wrong shape scores a category it is not
// in; a plant in a light file tests set B's ground again instead of ordinary source; and a deleted
// line numbered on the wrong side of the host's own hunks anchors the answer on a line the range
// never shows. The plant table is append-only, so a duplicate number or a file planted twice with
// one category would quietly change what an existing variant means.

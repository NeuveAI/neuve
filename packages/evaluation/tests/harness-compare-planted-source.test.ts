const file = (
  path: string,
  added: ReadonlyArray<string>,
  deleted: ReadonlyArray<string> = [],
  extra: { head?: string | undefined; existedBefore?: boolean } = {},
) => ({
  path,
  added,
  deleted,
  head: "head" in extra ? extra.head : "package x\n",
  existedBefore: extra.existedBefore ?? true,
});

const context = (
  hostFiles: ReadonlyArray<string>,
  relatedPaths: ReadonlyArray<string> = [],
) => ({ hostFiles: new Set(hostFiles), relatedPaths });

test("ordinary source excludes every light class, new and deleted files, and unknown languages", () => {
  const code = ["\tif n > limit {", "\t\treturn errTooMany", "\t}"];
  expect(ordinarySourceProblem(file("internal/x/x.go", code))).toBeNull();
  expect(
    ordinarySourceProblem(file("src/x.py", ["    return value"])),
  ).toBeNull();
  expect(ordinarySourceProblem(file("go.sum", code))).toMatch(/lockfile/);
  expect(ordinarySourceProblem(file("internal/x/x_test.go", code))).toMatch(
    /tests/,
  );
  expect(ordinarySourceProblem(file("src/a.test.ts", ["run();"]))).toMatch(
    /tests/,
  );
  expect(ordinarySourceProblem(file("docs/x.md", ["text"]))).toMatch(/docs/);
  expect(ordinarySourceProblem(file("testdata/x.go", code))).toMatch(
    /fixtures|tests/,
  );
  expect(
    ordinarySourceProblem(
      file("x_string.go", code, [], {
        head: "// Code generated by stringer; DO NOT EDIT.\n",
      }),
    ),
  ).toMatch(/generated/);
  expect(
    ordinarySourceProblem(file("src/a.ts", ['import { b } from "./b";'])),
  ).toMatch(/import-only/);
  // An object property alone is a declaration-shaped edit, which a light review would take.
  expect(
    ordinarySourceProblem(file("src/a.js", ["  forceError: isErrored,"])),
  ).toMatch(/declaration-only/);
  expect(
    ordinarySourceProblem(
      file("src/a.ts", ["run();"], [], { existedBefore: false }),
    ),
  ).toMatch(/new file/);
  expect(
    ordinarySourceProblem(
      file("src/a.ts", [], ["run();"], { head: undefined }),
    ),
  ).toMatch(/deleted/);
  expect(ordinarySourceProblem(file("BUILD.gn", ["deps = []"]))).toMatch(
    /language/,
  );
  expect(ordinarySourceProblem(file("vendor/x/x.go", code))).toMatch(
    /vendored/,
  );
});

test("each category's shape is enforced on the plant's own diff", () => {
  const changed = file("cmd/a/a.go", ["\tif x == nil {"], ["\tif x != nil {"]);
  const deletedOnly = file("cmd/a/a.go", [], ["\twg.Wait()"]);
  const host = ["cmd/a/a.go", "cmd/a/a_test.go"];

  // A source defect lives in a file the host's change touches.
  expect(
    sourceShapeProblem("source-defect", [changed], context(host)),
  ).toBeNull();
  expect(
    sourceShapeProblem("source-defect", [changed], context(["cmd/b/b.go"])),
  ).toMatch(/touches/);
  expect(
    sourceShapeProblem("source-defect", [deletedOnly], context(host)),
  ).toMatch(/adds/);

  // Removed behaviour deletes only, and names what still needs it.
  expect(
    sourceShapeProblem(
      "removed-behaviour",
      [deletedOnly],
      context(host, ["cmd/a/a.go"]),
    ),
  ).toBeNull();
  expect(
    sourceShapeProblem(
      "removed-behaviour",
      [changed],
      context(host, ["cmd/a/a.go"]),
    ),
  ).toMatch(/deletes lines only/);
  expect(
    sourceShapeProblem("removed-behaviour", [deletedOnly], context(host)),
  ).toMatch(/related/);

  // Cross-file names a dependent file the plant leaves alone.
  expect(
    sourceShapeProblem("cross-file", [changed], context(host, ["cmd/b/b.go"])),
  ).toBeNull();
  expect(
    sourceShapeProblem("cross-file", [changed], context(host, ["cmd/a/a.go"])),
  ).toMatch(/does not touch/);
  expect(sourceShapeProblem("cross-file", [changed], context(host))).toMatch(
    /related/,
  );

  // Missing test needs a host whose range changes tests, and touches no test itself.
  expect(
    sourceShapeProblem("missing-test", [changed], context(host)),
  ).toBeNull();
  expect(
    sourceShapeProblem("missing-test", [changed], context(["cmd/a/a.go"])),
  ).toMatch(/changes tests/);
  expect(
    sourceShapeProblem(
      "missing-test",
      [file("cmd/a/a_test.go", ["\tt.Fatal(x)"])],
      context(host),
    ),
  ).toMatch(/tests/);

  // Out of scope sits in a module none of the host's files lives in.
  const stray = file("cmd/c/c.go", ["\tlog.Fatal(err)"]);
  expect(sourceShapeProblem("out-of-scope", [stray], context(host))).toBeNull();
  expect(sourceShapeProblem("out-of-scope", [changed], context(host))).toMatch(
    /outside/,
  );
  expect(
    sourceShapeProblem(
      "out-of-scope",
      [file("cmd/a/other.go", ["x()"])],
      context(host),
    ),
  ).toMatch(/module/);

  // One file per plant.
  expect(
    sourceShapeProblem("source-defect", [changed, stray], context(host)),
  ).toMatch(/exactly one/);
});


// Why: the set is frozen once pinned. Without the build enforcing it, deleting a variant's folder
// or its entry, or editing an entry, silently re-pinned a different variant under the same number.
test("the build enforces the pinned set; only --replace changes a pinned variant", async () => {
  const { buildSourceSet, verifySourceSet } =
    await import("../src/harness-compare/full-test/planted-source.ts");
  const { join } = await import("node:path");
  const { existsSync, readFileSync, rmSync } = await import("node:fs");
  const { root, hosts, cases, plant } = await fixtureHost();
  try {
    const index = join(root, "set-c.json");
    const build = (plants: ReadonlyArray<PlantSpec>, replace?: number) =>
      buildSourceSet({
        hostsRoot: hosts,
        casesRoot: cases,
        plants,
        index,
        ...(replace === undefined ? {} : { replace }),
      });
    build([plant]);
    const pinned = readFileSync(index, "utf8");
    const folder = join(cases, "planted", "101");
    // A pinned number with no entry is refused.
    expect(() => build([])).toThrow(/never removed/);
    // A missing folder rebuilds only to the pinned bytes.
    rmSync(folder, { recursive: true, force: true });
    expect(build([plant]).results[0]!.state).toBe("built");
    expect(readFileSync(index, "utf8")).toBe(pinned);
    const edited = { ...plant, message: "Tighten the limit check" };
    rmSync(folder, { recursive: true, force: true });
    expect(() => build([edited])).toThrow(
      /pinned and its result differs.*--replace 101/,
    );
    expect(existsSync(folder)).toBe(false);
    expect(readFileSync(index, "utf8")).toBe(pinned);
    build([plant]);
    // --replace is the one way, for a pinned number only, and it reports both sets of hashes.
    expect(() => build([plant], 999)).toThrow(/not pinned/);
    const replaced = build([edited], 101);
    expect(replaced.replacement?.before.commit).not.toBe(
      replaced.replacement?.after.commit,
    );
    expect(replaced.replacement?.before.planted).not.toBe(
      replaced.replacement?.after.planted,
    );
    expect(existsSync(join(cases, "planted", ".101.replaced"))).toBe(false);
    // A --replace that fails restores the pinned folder as it was and leaves no backup.
    const before = readFileSync(join(folder, "planted.json"), "utf8");
    expect(() =>
      build(
        [{ ...edited, edits: [{ find: "no such text", replace: "x" }] }],
        101,
      ),
    ).toThrow(/edit not found/);
    expect(readFileSync(join(folder, "planted.json"), "utf8")).toBe(before);
    expect(existsSync(join(cases, "planted", ".101.replaced"))).toBe(false);
    expect(
      verifySourceSet({ hostsRoot: hosts, index, plants: [edited] }).problems,
    ).toEqual([]);
  } finally {
    rmSync(root, { recursive: true, force: true });
  }
});


const objectsOf = (replay: string) =>
  Bun.spawnSync([
    "git",
    "-C",
    replay,
    "cat-file",
    "--batch-all-objects",
    "--batch-check=%(objectname)",
  ])
    .stdout.toString()
    .trim()
    .split("\n")
    .sort();

// Why: checking an existing variant must never write into its pinned clone. A refused build used
// to leave the re-derived (different) commit behind as an unreachable object, so the variant then
// failed its own leakage check for good and nothing more could be appended.
test("a refused build and a verify leave the pinned clone's objects untouched", async () => {
  const { buildSourceSet, verifySourceSet } =
    await import("../src/harness-compare/full-test/planted-source.ts");
  const { join } = await import("node:path");
  const { rmSync } = await import("node:fs");
  const { root, hosts, cases, plant } = await fixtureHost();
  try {
    const index = join(root, "set-c.json");
    const first = buildSourceSet({
      hostsRoot: hosts,
      casesRoot: cases,
      plants: [plant],
      index,
    });
    expect(first.results.map((r) => r.state)).toEqual(["built"]);
    const replay = join(cases, "planted", "101", "replay");
    const before = objectsOf(replay);
    // An edited entry no longer matches its built variant: refused.
    expect(() =>
      buildSourceSet({
        hostsRoot: hosts,
        casesRoot: cases,
        plants: [{ ...plant, message: "Tidy the limit check again" }],
        index,
      }),
    ).toThrow(/differs|is not/);
    expect(
      verifySourceSet({ hostsRoot: hosts, index, plants: [plant] }).problems,
    ).toEqual([]);
    expect(objectsOf(replay)).toEqual(before);
    // The variant still re-derives unchanged with its own entry.
    const again = buildSourceSet({
      hostsRoot: hosts,
      casesRoot: cases,
      plants: [plant],
      index,
    });
    expect(again.results.map((r) => r.state)).toEqual(["unchanged"]);
    // A missing variant is reported, not thrown.
    rmSync(join(cases, "planted", "101"), { recursive: true, force: true });
    const missing = verifySourceSet({
      hostsRoot: hosts,
      index,
      plants: [plant],
    });
    expect(missing.problems.some((p) => /case\.json is missing/.test(p))).toBe(
      true,
    );
  } finally {
    rmSync(root, { recursive: true, force: true });
  }
});


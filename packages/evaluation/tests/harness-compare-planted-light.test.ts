// Why (NEU-148, 12.33's guard): set B decides whether a unit review at a forced pack size still
// catches problems planted in light files. Two boundaries would corrupt it silently: a plant whose
// own diff is not of its light class (then the benchmark tests the full path, not the light one),
// and a scorer that counts a catch the step never made, or misses one it did, or files a unit under
// the wrong part of its pack.
import { expect, test } from "bun:test";
import {
  checkKind,
  lightShapeProblem,
} from "../src/harness-compare/full-test/planted.ts";
import type { StoredRun } from "../src/harness-compare/full-test/packets.ts";
import type { PlantedRecord } from "../src/harness-compare/full-test/planted-light.ts";
import {
  positionEffect,
  quarterOf,
  scorePlant,
  scorePlanted,
} from "../src/harness-compare/full-test/unit-review-score.ts";

test("a plant's own diff must have its light class's shape, and an old-side plant is judged on the base side", () => {
  expect(
    lightShapeProblem("light-deletion-only", [
      {
        path: "a.ts",
        added: [],
        deleted: ["if (x > 1) {", "  throw new Error('x');", "}"],
      },
    ]),
  ).toBeNull();
  expect(
    lightShapeProblem("light-deletion-only", [
      { path: "a.ts", added: ["y()"], deleted: [] },
    ]),
  ).toMatch(/adds lines/);
  expect(
    lightShapeProblem("light-import-only", [
      { path: "a.go", added: ['\t"math/rand"'], deleted: ['\t"crypto/rand"'] },
    ]),
  ).toBeNull();
  expect(
    lightShapeProblem("light-import-only", [
      { path: "a.ts", added: ["run();"], deleted: [] },
    ]),
  ).toMatch(/not imports/);
  expect(
    lightShapeProblem("light-declaration-only", [
      {
        path: "x/index.ts",
        added: ["export * from './internal';", "export type Kind = string;"],
        deleted: [],
      },
    ]),
  ).toBeNull();
  expect(
    lightShapeProblem("light-tests", [
      { path: "src/a.ts", added: ["x"], deleted: [] },
    ]),
  ).toMatch(/not a test file/);
  expect(
    lightShapeProblem("light-generated", [
      {
        path: "z_gen.go",
        added: ["x"],
        deleted: [],
        head: "// Code generated by stringer; DO NOT EDIT.\n",
      },
    ]),
  ).toBeNull();
  expect(
    lightShapeProblem("light-generated", [
      { path: "z.go", added: ["x"], deleted: [], head: "package z\n" },
    ]),
  ).toMatch(/no generated marker/);
  // A deleted guard's lines exist only on the old side.
  expect(
    checkKind(
      "light-deletion-only",
      new Map(),
      [{ path: "a.ts", side: "old", startLine: 4, endLine: 6 }],
      new Map([["a.ts", [[4, 6]]]]),
    ),
  ).toBeNull();
  expect(
    checkKind(
      "light-deletion-only",
      new Map(),
      [{ path: "a.ts", side: "old", startLine: 9, endLine: 9 }],
      new Map([["a.ts", [[4, 6]]]]),
    ),
  ).toMatch(/must be changed lines/);
});

const planted = (overrides: Partial<PlantedRecord> = {}): PlantedRecord => ({
  version: 1,
  caseId: "planted:x",
  variant: 1,
  host: { caseId: "h", source: "t3code", number: 1, base: "b", head: "h" },
  problem: "lockfile-registry-swap",
  kind: "light-lockfile",
  style: "look-alike registry",
  bucket: "late",
  aimed: { rank: 14, units: 20, position: 14, order: "directory, path, line" },
  commit: "c",
  message: "Refresh lockfile",
  description: "d",
  lines: [{ path: "yarn.lock", side: "new", startLine: 7, endLine: 7 }],
  lineKeys: ["yarn.lock:new:7"],
  mentions: ["registry.npmjs-mirror.org", "lodash"],
  expected:
    "a request for changes citing the planted lines, or a person's lane (human-suggested or human-required) with the plant named in what was checked",
  ...overrides,
});

const unit = (
  id: string,
  line: number,
  lane: string | null,
  extra: Record<string, unknown> = {},
) => ({
  unitId: id,
  local: `g1.${id}`,
  recorded: {
    kind: "unit.recorded@2",
    payload: {
      title: id,
      ownedRanges: [
        {
          kind: "lines",
          path: "yarn.lock",
          side: "new",
          startLine: line,
          endLine: line,
        },
      ],
    },
  },
  ...(lane === null
    ? {}
    : {
        assessment: {
          id: `a-${id}`,
          kind: "assessment.recorded@3",
          payload: { lane },
        },
      }),
  content: {},
  references: [],
  comments: [],
  ...extra,
});

const run = (units: ReadonlyArray<unknown>) =>
  ({
    packet: { complete: true, gaps: [], batches: [{ batchId: "b", units }] },
    manifest: { hunks: [] },
  }) as unknown as StoredRun;

const record = (
  u: string,
  position: number,
  rawVerdict: "approve" | "request-changes" | null,
  outcome = "ok",
) => ({
  unit: u,
  pack: "p1",
  packSize: 16,
  position,
  outcome,
  rawVerdict,
});

test("a plant is caught by a request for changes citing it, or by a person's lane that names it; never by an unassessed unit", () => {
  // A person's lane whose what-was-checked names the look-alike registry.
  const named = scorePlant(
    planted(),
    run([
      unit("u1", 7, "human-suggested", {
        content: {
          checked:
            "Checked yarn.lock: lodash now resolves from registry.npmjs-mirror.org.",
        },
      }),
    ]),
    [record("u1", 14, "approve")],
  );
  expect(named).toMatchObject({
    caught: true,
    how: "a person's lane, named",
    position: { position: 14 },
  });
  // Agentic and silent about it: missed.
  const missed = scorePlant(
    planted(),
    run([
      unit("u1", 7, "agentic", { content: { checked: "Checked versions." } }),
    ]),
    [record("u1", 3, "approve")],
  );
  expect(missed.caught).toBe(false);
  // A request for changes resting on a defect anchored at the planted line.
  const requested = scorePlant(
    planted(),
    run([
      unit("u1", 7, "agentic", {
        disposition: {
          id: "d",
          kind: "disposition.recorded@2",
          payload: { verdict: "request-changes", restsOn: ["c1"], proof: [] },
        },
        comments: [
          {
            id: "c1",
            kind: "comment.recorded@2",
            payload: {
              body: "b",
              anchor: {
                path: "yarn.lock",
                side: "new",
                startLine: 7,
                endLine: 7,
              },
              finding: { kind: "defect", about: "code", evidence: [] },
            },
          },
        ],
      }),
    ]),
    [record("u1", 2, "request-changes")],
  );
  expect(requested).toMatchObject({ caught: true, how: "request for changes" });
  // The unit fell back with no assessment: not caught, and said so.
  const fallback = scorePlant(planted(), run([unit("u1", 7, null)]), [
    record("u1", 9, null, "failed"),
  ]);
  expect(fallback).toMatchObject({ caught: false, unassessed: 1 });
  const summary = scorePlanted([named, missed, requested, fallback]);
  expect(summary).toMatchObject({ variants: 4, caught: 2, guardHolds: false });
  expect(summary.byQuarter).toEqual({
    "quarter 4": { variants: 1, caught: 1 },
    "quarter 1": { variants: 2, caught: 1 },
    "quarter 3": { variants: 1, caught: 0 },
  });
});

test("the position effect compares each unit with itself at one unit per call, by the quarter of its pack", () => {
  expect([1, 4, 5, 8, 9, 12, 13, 16].map((p) => quarterOf(p, 16))).toEqual([
    1, 1, 2, 2, 3, 3, 4, 4,
  ]);
  expect(quarterOf(1, 1)).toBe(4);
  const base = {
    packet: run([unit("a", 1, "agentic"), unit("b", 30, "agentic")]).packet,
    records: [record("a", 1, "approve"), record("b", 1, "approve")],
  };
  const next = {
    packet: run([unit("x", 1, "agentic"), unit("y", 30, "human-suggested")])
      .packet,
    records: [record("x", 2, "approve"), record("y", 15, "request-changes")],
  };
  const effect = positionEffect([
    { caseId: "c", base, next, labelled: new Set(["yarn.lock:new:1"]) },
  ]);
  expect(effect.unmatched).toBe(0);
  expect(effect.quarters["quarter 1"]).toMatchObject({
    units: 1,
    verdictFlips: 0,
    laneFlips: 0,
    newRequests: 0,
  });
  // Late in its pack, the unit turned from approve to a request, on lines no reviewer marked.
  expect(effect.quarters["quarter 4"]).toMatchObject({
    units: 1,
    verdictFlips: 1,
    laneFlips: 1,
    newRequests: 1,
    newRequestsOnUnlabelled: 1,
  });
});

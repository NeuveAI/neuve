/**
 * Writes the real-packet Storybook fixture (M5 §3.7): one real review, read
 * from a repository's Records by the BFF's own page loads and projection, so
 * Storybook shows a real batch beside the designed one. Regenerate it when
 * the projection changes; never edit the output by hand.
 *
 *   bun run fixture:real-packet -- --repo <path> [--cycle <cycle id>] [--out <name>]
 *
 * The repository's newest cycle is read, or the one --cycle names: every batch's overview, and the
 * desk of each human-required unit, of one human-suggested unit per batch
 * and of the units with an agent's comment. People's dispositions, comments and feedback are
 * left out, so the fixture shows the batch as the review published it; what feedback answers on
 * is kept.
 */
import { writeFile } from "node:fs/promises"
import { join, resolve } from "node:path"
import { parseArgs } from "node:util"

import type {
  BatchOverviewData,
  DeskFeedback,
  FeedbackTarget,
  ReviewDeskData,
} from "@workspace/ui/neuve/types"

const { values } = parseArgs({
  options: {
    repo: { type: "string" },
    cycle: { type: "string" },
    // Another fixture file beside the default (`real-sections` writes real-sections.fixtures.ts).
    out: { type: "string" },
  },
})
const name = values.out ?? "real-packet"
if (values.repo === undefined || !/^[a-z]+(-[a-z]+)*$/.test(name)) {
  console.error(
    "Usage: bun run fixture:real-packet -- --repo <path> [--cycle <cycle id>] [--out <name>]"
  )
  process.exit(2)
}
/** `real-packet` → `realPacket`, the prefix of the file's exports. */
const exportPrefix = name.replace(/-([a-z])/g, (_, letter: string) =>
  letter.toUpperCase()
)
process.env["NEUVE_REPOSITORY"] = resolve(values.repo)
const { deskLoad, newestBatchIds, overviewLoad } =
  await import("../src/server/desk.server")

/** Desks carry what feedback answers on, as with the owner's setting on. */
const WITH_FEEDBACK = { feedback: true }

/** The fixture's reader, as the designed fixtures name them. */
const READER = { id: "reviewer-local", name: "You", initials: "VD" }

/** What feedback answers on, without anyone's answers (M5 S7). */
const unanswered = (feedback: DeskFeedback): DeskFeedback => {
  const bare = <T extends FeedbackTarget>(target: T): T => {
    const { saved: _saved, ...rest } = target
    return rest as T
  }
  const each = <T extends FeedbackTarget>(
    targets: Partial<Record<string, T>>
  ): Record<string, T> =>
    Object.fromEntries(
      Object.entries(targets).flatMap(([key, target]) =>
        target ? [[key, bare(target)]] : []
      )
    )
  return {
    ...(feedback.unit ? { unit: bare(feedback.unit) } : {}),
    findings: each(feedback.findings),
    references: each(feedback.references),
    digests: each(feedback.digests),
  }
}

/** The desk as the review published it: no person's work on it. */
const published = (data: ReviewDeskData): ReviewDeskData => {
  const { currentDecision: _decided, feedback, ...rest } = data
  return {
    ...rest,
    ...(feedback ? { feedback: unanswered(feedback) } : {}),
    reviewer: READER,
    humanDecidedUnitIds: [],
    commentRecords: (data.commentRecords ?? []).filter(
      (record) => record.author.kind === "agent"
    ),
    commentSnapshotSequence: 0,
  }
}

const overviews: Array<BatchOverviewData> = []
const desks: Record<string, ReviewDeskData> = {}
for (const batchId of await newestBatchIds(values.cycle)) {
  const load = await overviewLoad(batchId, { people: false })
  if (load.status !== "ready") continue
  overviews.push(load.data)
  const opened = (await deskLoad(load.data.firstUnitId, WITH_FEEDBACK)).load
  if (opened.status !== "ready") continue
  for (const unit of opened.data.batchUnits) {
    const data =
      unit.id === opened.data.unit.id
        ? opened
        : (await deskLoad(unit.id, WITH_FEEDBACK)).load
    if (data.status !== "ready") continue
    // Every human-required unit and one human-suggested unit per batch.
    const invited =
      unit.lane === "human-required" ||
      (unit.lane === "human-suggested" &&
        !Object.values(desks).some(
          (taken) =>
            taken.batchTitle === data.data.batchTitle &&
            taken.unit.lane === "human-suggested"
        ))
    const commented = (data.data.commentRecords ?? []).some(
      (record) => record.author.kind === "agent"
    )
    if (invited || commented) desks[unit.id] = published(data.data)
  }
}
const first = overviews.at(0)
if (first === undefined) {
  console.error("No published review in that repository's Records.")
  process.exit(1)
}
const out = join(
  import.meta.dir,
  `../../../packages/ui/src/fixtures/${name}.fixtures.ts`
)
await writeFile(
  out,
  `/*
 * GENERATED by \`bun run fixture:real-packet${name === "real-packet" ? "" : ` -- --out ${name}`}\` (apps/neuve-web/apps/web/scripts/real-packet-fixture.ts)
 * from a real review in Records (range ${first.branch}, head ${first.revision}), through the BFF's
 * page loads and projection. Do not edit by hand: regenerate it when the projection changes.
 * People's dispositions, comments and feedback are left out.
 */
import type { BatchOverviewData, ReviewDeskData } from "@workspace/ui/neuve/types"

/** Every batch of the real packet, in packet order. */
export const ${exportPrefix}OverviewFixtures: Array<BatchOverviewData> = ${JSON.stringify(overviews, null, 2)}

/** The desks of the units that need or invite a person, or carry an agent's comment, by unit ID. */
export const ${exportPrefix}DeskFixtures: Record<string, ReviewDeskData> = ${JSON.stringify(desks, null, 2)}
`
)
console.log(
  `Wrote ${out}: ${overviews.length} batch overview(s), ${Object.keys(desks).length} desk(s).`
)

import * as React from "react"
import { ArrowUpIcon } from "lucide-react"

import { cn } from "@workspace/ui/lib/utils"
import { pathParts } from "@workspace/ui/neuve/review-desk/reference-tie"
import type {
  ReviewLane,
  UnitExclusion,
  UntitledFile,
} from "@workspace/ui/neuve/types"

/*
 * What a unit's row says about its review lane beyond the lane itself, in
 * the same words and parts on every surface that lists units: the batch
 * overview, the Reviews page, the desk's rail and the unit page. Each
 * surface keeps its own layout around them.
 */

/** The review lanes by their full names (vocabulary.md). */
export const LANE_NAME: Record<ReviewLane, string> = {
  "human-required": "Human-required",
  "human-suggested": "Human-suggested",
  "agentic-review": "Agentic review",
  "static-automation": "Static automation",
}

/** Said of a unit (or one change of it) no agent decided in this run. */
export const NO_AGENT_DECISION = "No agent decision in this run"

/**
 * A unit no agent read, as every surface says it: the state ("Lockfile,
 * not read") and the rule that marked it, in plain words. Records' reasons
 * are an open set: one this build does not know claims no kind of file
 * (the published vendored list also matches hand-written files), and its
 * raw name is never shown. The mark never approves the unit.
 */
export function excludedWords(excluded: UnitExclusion): {
  state: string
  rule: string
} {
  switch (excluded.reason) {
    case "lockfile":
      return {
        state: "Lockfile, not read",
        rule: "Marked a lockfile by its file name",
      }
    case "declared-generated":
      return {
        state: "Generated file, not read",
        rule: "Marked generated by this repository’s own declarations",
      }
    default:
      return { state: "Not read", rule: "Marked to skip reading" }
  }
}

/** The rail's own group of the units no agent read. */
export const NOT_READ_LABEL = "Not read"

/** "2 files not read": the overview's one count of them, whatever marked them. */
export const notReadCount = (count: number) =>
  `${count} file${count === 1 ? "" : "s"} not read`

/** "Moved up from Agentic review": a unit whose review lane rose since the last run. */
export const movedUpLabel = (from: ReviewLane) =>
  `Moved up from ${LANE_NAME[from]}`

/**
 * The moved-up mark: one muted 12px upward arrow, no colour and no reason.
 * Named, it says its words in visually hidden text, so a link around it, or
 * one that points at it with `aria-describedby`, reads them. Unnamed, the
 * surface says them itself.
 */
export function MovedUpMark({
  from,
  named = true,
  id,
  className,
}: {
  from: ReviewLane
  named?: boolean
  id?: string
  className?: string
}) {
  return (
    <span
      id={id}
      className={cn("inline-flex shrink-0 text-ink-muted", className)}
    >
      <ArrowUpIcon aria-hidden="true" strokeWidth={2} className="size-3" />
      {named && <span className="sr-only">{movedUpLabel(from)}</span>}
    </span>
  )
}

/** "L12–48", or "L90" for one line. */
function lineSpan({ start, end }: { start: number; end: number }) {
  return start === end ? `L${start}` : `L${start}–${end}`
}

/**
 * How a unit with no written title is named: its first file's name, the
 * lines it owns there ("L12–48, L71–90 · +1 file") and the folder. Null for
 * a unit with a written title, whose title is its name.
 */
export function untitledName(
  untitled: { files: ReadonlyArray<UntitledFile> } | undefined
) {
  const [file, ...others] = untitled?.files ?? []
  if (!file) return null
  const within = [
    file.lines.map(lineSpan).join(", "),
    others.length > 0
      ? `+${others.length} file${others.length > 1 ? "s" : ""}`
      : "",
  ]
    .filter(Boolean)
    .join(" · ")
  return { ...pathParts(file.path), within }
}

export type UntitledNameParts = NonNullable<ReturnType<typeof untitledName>>

/*
 * The visible parts of an untitled unit's name are hidden from assistive
 * tech: the title, said in a hidden span by the surface, is its name.
 */

/** The owned lines of an untitled unit, quiet beside its file's name. */
export function UntitledLines({
  name,
  className,
}: {
  name: UntitledNameParts
  className?: string
}) {
  if (!name.within) return null
  // Each range stays whole when the list wraps: it breaks only between
  // ranges, never inside one ("L127–" / "140").
  const pieces = name.within.split(", ")
  return (
    <span
      aria-hidden="true"
      className={cn(
        "font-mono text-[11px] font-normal tracking-normal text-ink-muted",
        className
      )}
    >
      {pieces.map((piece, index) => (
        <React.Fragment key={index}>
          {index > 0 && ", "}
          <span className="whitespace-nowrap">{piece}</span>
        </React.Fragment>
      ))}
    </span>
  )
}

/**
 * An untitled unit's folder, quiet. Its end says the most: right-to-left
 * flow puts the ellipsis at its start; the bdi keeps the path reading left
 * to right (as the reference card's PathLabel does).
 */
export function UntitledFolder({
  name,
  className,
}: {
  name: UntitledNameParts
  className?: string
}) {
  if (!name.folder) return null
  return (
    <span
      aria-hidden="true"
      dir="rtl"
      className={cn(
        "min-w-0 truncate text-left font-mono font-normal tracking-normal text-ink-muted",
        className
      )}
    >
      <bdi dir="ltr">{name.folder}</bdi>
    </span>
  )
}
